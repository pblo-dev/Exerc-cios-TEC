# programa que peça ao usurário para inserir a largura e o comprimento de uma sala. Uma vez que os valores tenham sido lidos, seu programa deve calcular e exibir área da sala
largura = float(input('Digite a largura da sala: '))
comprimento = float(input('Digite o comprimento da sala: '))
area_da_sala = largura * comprimento
print('A área da sala é: ', area_da_sala)